import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { createClient } from "@supabase/supabase-js";

const PROJECT_ROOT = process.cwd();
const OUTPUT_PATH = path.join(PROJECT_ROOT, "src", "lib", "i18n", "product-permalinks.generated.js");
const TARGET_LANGUAGES = ["en", "de", "fr", "es"];

// Exact match to the dashboard's slugify() (lib/slug.ts), confirmed by the
// dashboard agent - deliberately does NOT transliterate accented characters
// (é/ü/ñ/ö/ß etc. collapse into a hyphen like any other punctuation, they do
// not become e/u/n/o/ss). Slugs must be byte-for-byte reproducible from this
// same function or non-Dutch slugs will diverge from what the dashboard
// would produce for the same string.
function slugify(input) {
  return input
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

async function loadEnvLocal() {
  try {
    const content = await readFile(path.join(PROJECT_ROOT, ".env.local"), "utf8");
    const env = {};
    for (const line of content.split("\n")) {
      const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
      if (match) env[match[1]] = match[2].trim();
    }
    return env;
  } catch {
    return {};
  }
}

function dedupeSlugs(entries, language) {
  const seen = new Map();
  for (const entry of entries) {
    const slug = entry.slugs[language];
    if (!seen.has(slug)) {
      seen.set(slug, [entry]);
    } else {
      seen.get(slug).push(entry);
    }
  }
  for (const [slug, group] of seen) {
    if (group.length <= 1) continue;
    group.forEach((entry, i) => {
      if (i === 0) return; // first one keeps the clean slug
      entry.slugs[language] = `${slug}-${entry.id.slice(0, 8)}`;
    });
  }
}

async function generate() {
  const env = { ...(await loadEnvLocal()), ...process.env };
  const supabaseUrl = env.NEXT_PUBLIC_SUPABASE_URL;
  const supabaseAnonKey = env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  const storeId = env.NEXT_PUBLIC_STORE_ID;

  if (!supabaseUrl || !supabaseAnonKey || !storeId) {
    console.log("generate-product-permalinks: Supabase not configured, skipping (offline/local fallback mode).");
    return;
  }

  const supabase = createClient(supabaseUrl, supabaseAnonKey);

  const { data: products, error: productsError } = await supabase
    .from("products")
    .select("id, name, slug")
    .eq("store_id", storeId)
    .eq("status", "active");
  if (productsError) throw productsError;

  const ids = (products || []).map((p) => p.id);
  const { data: translations, error: translationsError } = ids.length
    ? await supabase
        .from("translations")
        .select("entity_id, locale, value")
        .eq("store_id", storeId)
        .eq("entity_type", "product")
        .eq("field_name", "name")
        .in("entity_id", ids)
        .in("locale", TARGET_LANGUAGES)
    : { data: [], error: null };
  if (translationsError) throw translationsError;

  const namesByProduct = {};
  (translations || []).forEach((row) => {
    if (!namesByProduct[row.entity_id]) namesByProduct[row.entity_id] = {};
    namesByProduct[row.entity_id][row.locale] = row.value;
  });

  const entries = (products || []).map((product) => {
    const slugs = { nl: product.slug };
    TARGET_LANGUAGES.forEach((lang) => {
      const sourceName = namesByProduct[product.id]?.[lang] || product.name;
      slugs[lang] = slugify(sourceName);
    });
    return { id: product.id, slugs };
  });

  TARGET_LANGUAGES.forEach((lang) => dedupeSlugs(entries, lang));

  const output = [
    "// Auto-generated by scripts/generate-product-permalinks.mjs - do not edit by hand.",
    "// Regenerated on every build (prebuild script) from live product/translation data.",
    "// Run `node scripts/generate-product-permalinks.mjs` to regenerate manually.",
    `export const PRODUCT_PERMALINKS = ${JSON.stringify(entries, null, 2)};`,
    "",
  ].join("\n");

  await writeFile(OUTPUT_PATH, output, "utf8");
  console.log(`generate-product-permalinks: wrote ${entries.length} product(s) to ${OUTPUT_PATH}`);
}

await generate();
