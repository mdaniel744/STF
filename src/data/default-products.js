const specPrefixes = {
  en: { approx: "approx.", notApplicable: "n/a" },
  fr: { approx: "env.", notApplicable: "n/a" },
  de: { approx: "ca.", notApplicable: "n. z." },
  es: { approx: "aprox.", notApplicable: "n/a" },
};

function localizeSpecValue(value, language) {
  if (!value || language === "nl") return value;
  const spec = specPrefixes[language];
  if (!spec) return value;
  return value
    .replace(/^ca\./, spec.approx)
    .replace(/^n\.v\.t\.$/, spec.notApplicable);
}

export function localizeDefaultProduct(product, language) {
  if (!product || language === "nl" || !product.id?.startsWith("default-")) return product;

  const translated = defaultProductTranslations[product.id]?.[language];
  if (!translated) return product;

  return {
    ...product,
    ...translated,
    specs_weight: localizeSpecValue(product.specs_weight, language),
    specs_volume: localizeSpecValue(product.specs_volume, language),
    specs_payload: localizeSpecValue(product.specs_payload, language),
  };
}

function sortProducts(products, sort = "-created_date") {
  const direction = sort.startsWith("-") ? -1 : 1;
  const field = sort.replace(/^-/, "");

  return [...products].sort((a, b) => {
    const aValue = a[field] ?? "";
    const bValue = b[field] ?? "";

    if (field === "price") return (aValue - bValue) * direction;
    return String(aValue).localeCompare(String(bValue)) * direction;
  });
}

function matchesValue(product, key, value) {
  if (!value) return true;
  if (key === "color") {
    return product.color === value || product.available_colors?.includes(value);
  }
  return product[key] === value;
}

export function listDefaultProducts(sort = "-created_date", limit = 100) {
  return sortProducts(defaultProducts, sort).slice(0, limit);
}

export function filterDefaultProducts(query = {}, sort = "-created_date", limit = 100) {
  const entries = Object.entries(query).filter(([, value]) => value);
  const filtered = defaultProducts.filter((product) =>
    entries.every(([key, value]) => matchesValue(product, key, value))
  );
  return sortProducts(filtered, sort).slice(0, limit);
}

export function findDefaultProductBySlugOrId(slugOrId) {
  return defaultProducts.find((product) => product.slug === slugOrId || product.id === slugOrId) || null;
}
